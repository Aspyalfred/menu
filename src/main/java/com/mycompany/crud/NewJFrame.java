    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
       // Get values from the form
    String idText = txtID.getText().trim();
    String name = txtName.getText().trim();
    String department = cmbDepartment.getSelectedItem().toString();
    String position = txtPosition.getText().trim();
    String salaryText = txtSalary.getText().trim();

    // Check required fields
    if (idText.isEmpty()) {
        JOptionPane.showMessageDialog(
            this,
            "Please enter Employee ID."
        );
        txtID.requestFocus();
        return;
    }

    if (name.isEmpty()) {
        JOptionPane.showMessageDialog(
            this,
            "Please enter Full Name."
        );
        txtName.requestFocus();
        return;
    }

    if (position.isEmpty()) {
        JOptionPane.showMessageDialog(
            this,
            "Please enter Position."
        );
        txtPosition.requestFocus();
        return;
    }

    if (salaryText.isEmpty()) {
        JOptionPane.showMessageDialog(
            this,
            "Please enter Salary."
        );
        txtSalary.requestFocus();
        return;
    }

    try {

        int id = Integer.parseInt(idText);
        double salary = Double.parseDouble(salaryText);

        String sql =
            "INSERT INTO Employees " +
            "([ID], [Name], [Department], [Position], [Salary]) " +
            "VALUES (?, ?, ?, ?, ?)";

        try (
            Connection con = MSConnect.conn();
            PreparedStatement pst = con.prepareStatement(sql)
        ) {

            if (con == null) {
                return;
            }

            pst.setInt(1, id);
            pst.setString(2, name);
            pst.setString(3, department);
            pst.setString(4, position);
            pst.setDouble(5, salary);

            pst.executeUpdate();

            JOptionPane.showMessageDialog(
                this,
                "Employee Added Successfully!"
            );

            loadEmployees();

            // Clear fields
            txtID.setText("");
            txtName.setText("");
            cmbDepartment.setSelectedIndex(0);
            txtPosition.setText("");
            txtSalary.setText("");

        }

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
            this,
            "Employee ID and Salary must be numbers."
        );

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
            this,
            "Database Error:\n" + e.getMessage()
        );
    }

    }//GEN-LAST:event_btnAddActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
      String idText = txtID.getText().trim();
    String name = txtName.getText().trim();
    String department = cmbDepartment.getSelectedItem().toString();
    String position = txtPosition.getText().trim();
    String salaryText = txtSalary.getText().trim();

    if (idText.isEmpty()) {
        JOptionPane.showMessageDialog(
            this,
            "Please enter Employee ID."
        );
        txtID.requestFocus();
        return;
    }

    if (name.isEmpty() || position.isEmpty() || salaryText.isEmpty()) {
        JOptionPane.showMessageDialog(
            this,
            "Please complete all employee details."
        );
        return;
    }

    try {

        int id = Integer.parseInt(idText);
        double salary = Double.parseDouble(salaryText);

        String sql =
            "UPDATE Employees SET " +
            "[Name] = ?, " +
            "[Department] = ?, " +
            "[Position] = ?, " +
            "[Salary] = ? " +
            "WHERE [ID] = ?";

        try (
            Connection con = MSConnect.conn();
            PreparedStatement pst = con.prepareStatement(sql)
        ) {

            if (con == null) {
                return;
            }

            pst.setString(1, name);
            pst.setString(2, department);
            pst.setString(3, position);
            pst.setDouble(4, salary);
            pst.setInt(5, id);

            int rows = pst.executeUpdate();

            if (rows > 0) {

                JOptionPane.showMessageDialog(
                    this,
                    "Employee Updated Successfully!"
                );

                loadEmployees();

            } else {

                JOptionPane.showMessageDialog(
                    this,
                    "Employee ID " + id + " was not found."
                );
            }
        }

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
            this,
            "Employee ID and Salary must be numbers."
        );

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
            this,
            "Database Error:\n" + e.getMessage()
        );
    }


    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
      
  String idText = txtID.getText().trim();

    if (idText.isEmpty()) {

        JOptionPane.showMessageDialog(
            this,
            "Please enter Employee ID to delete."
        );

        txtID.requestFocus();
        return;
    }

    try {

        int id = Integer.parseInt(idText);

        int confirm = JOptionPane.showConfirmDialog(
            this,
            "Are you sure you want to delete Employee ID " + id + "?",
            "Confirm Delete",
            JOptionPane.YES_NO_OPTION
        );

        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }

        String sql =
            "DELETE FROM Employees WHERE [ID] = ?";

        try (
            Connection con = MSConnect.conn();
            PreparedStatement pst = con.prepareStatement(sql)
        ) {

            if (con == null) {
                return;
            }

            pst.setInt(1, id);

            int rows = pst.executeUpdate();

            if (rows > 0) {

                JOptionPane.showMessageDialog(
                    this,
                    "Employee Deleted Successfully!"
                );

                loadEmployees();

                // Clear fields
                txtID.setText("");
                txtName.setText("");
                cmbDepartment.setSelectedIndex(0);
                txtPosition.setText("");
                txtSalary.setText("");

            } else {

                JOptionPane.showMessageDialog(
                    this,
                    "Employee ID " + id + " was not found."
                );
            }
        }

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(
            this,
            "Employee ID must be a number."
        );

    } catch (SQLException e) {

        JOptionPane.showMessageDialog(
            this,
            "Database Error:\n" + e.getMessage()
        );
    }

    }//GEN-LAST:event_btnDeleteActionPerformed

